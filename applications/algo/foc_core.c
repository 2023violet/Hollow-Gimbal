/**
 * @brief  Space Vector PWM Calculation (Optimized Standard 7-Segment)
 * 
 * @param  foc  Pointer to FOC variables structure (alpha/beta inputs, dtc_a/b/c outputs)
 * 
 * @return 0 on success (valid duties), -1 on saturation/NaN/error
 */
int foc_svpwm(struct foc_vars *foc)
{
    foc->v_alpha *= foc->inv_vbus;
    foc->v_beta *= foc->inv_vbus;

    float mag_sq = foc->v_alpha * foc->v_alpha + foc->v_beta * foc->v_beta;

    if (mag_sq > (FOC_TWO_THIRDS * FOC_TWO_THIRDS)) {
        float scale_factor = FOC_TWO_THIRDS / FOC_SQRT(mag_sq);
        foc->v_alpha *= scale_factor;
        foc->v_beta *= scale_factor;
    }

    if (foc->v_beta >= 0.0f) {
        if (foc->v_alpha >= 0.0f) {
            //quadrant I
            if (FOC_INV_SQRT3 * foc->v_beta > foc->v_alpha) {
                foc->sector = FOC_SECTOR_2; //sextant v2-v3
            } else {
                foc->sector = FOC_SECTOR_1; //sextant v1-v2
            }
        } else {
            //quadrant II
            if (-FOC_INV_SQRT3 * foc->v_beta > foc->v_alpha) {
                foc->sector = FOC_SECTOR_3; //sextant v3-v4
            } else {
                foc->sector = FOC_SECTOR_2; //sextant v2-v3
            }
        }
    } else {
        if (foc->v_alpha >= 0.0f) {
            //quadrant IV
            if (-FOC_INV_SQRT3 * foc->v_beta > foc->v_alpha) {
                foc->sector = FOC_SECTOR_5; //sextant v5-v6
            } else {
                foc->sector = FOC_SECTOR_6; //sextant v6-v1
            }
        } else {
            //quadrant III
            if (FOC_INV_SQRT3 * foc->v_beta > foc->v_alpha) {
                foc->sector = FOC_SECTOR_4; //sextant v4-v5
            } else {
                foc->sector = FOC_SECTOR_5; //sextant v5-v6
            }
        }
    }

    /* Convert the stationary vector to phase voltages and add a centered
     * common-mode component.  The timer receives active-high duty values;
     * its complementary outputs are generated by the timer peripheral. */
    foc_inv_clarke(foc);
    float phase_max = FOC_MAX(foc->v_a, FOC_MAX(foc->v_b, foc->v_c));
    float phase_min = FOC_MIN(foc->v_a, FOC_MIN(foc->v_b, foc->v_c));
    float common_mode = 0.5f * (phase_max + phase_min);

    foc->dtc_a = 0.5f + foc->v_a - common_mode;
    foc->dtc_b = 0.5f + foc->v_b - common_mode;
    foc->dtc_c = 0.5f + foc->v_c - common_mode;

    /* FOC_SVPWM_DUTY_MIN/MAX (see foc_config.h): sustained per-phase duty
     * above ~0.79 latches the DRV8311H half-bridges off, so the envelope is
     * tightened to the bench-proven window instead of the full [0, 1]. */
    foc->dtc_a = FOC_CLAMP(foc->dtc_a, FOC_SVPWM_DUTY_MIN, FOC_SVPWM_DUTY_MAX);
    foc->dtc_b = FOC_CLAMP(foc->dtc_b, FOC_SVPWM_DUTY_MIN, FOC_SVPWM_DUTY_MAX);
    foc->dtc_c = FOC_CLAMP(foc->dtc_c, FOC_SVPWM_DUTY_MIN, FOC_SVPWM_DUTY_MAX);

    return 0;
}

