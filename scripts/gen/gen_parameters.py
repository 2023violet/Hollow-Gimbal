"""Generate the Board1 parameter table, CLI module, test data and manual from parameters.json.

Usage (repository root):
  python -B scripts/gen/gen_parameters.py          write the generated files
  python -B scripts/gen/gen_parameters.py --check  exit 1 if any generated file is stale

Outputs:
  firmware/at32f415/include/foc_parameter_table.h
  firmware/at32f415/src/foc_parameter_table.c
  firmware/at32f415/tests/foc_parameter_documented.h
  tools/falconfoc-cli/falconfoc_params.py
  docs/parameters.md
Standard library only.
"""

import json
import struct
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "firmware/at32f415/parameters.json"

UNITS = {
    "none": 0, "A": 1, "rad": 2, "rad/s": 3, "count": 4, "us": 5, "V/A": 6, "V/(A*s)": 7,
    "A/(rad/s)": 8, "A/rad": 9, "1/s": 10, "ohm": 11, "H": 12, "Wb": 13, "N*m/A": 14,
    "kg*m^2": 15, "N*m*s/rad": 16, "Hz": 17, "V": 18, "ms": 20, "rad/s^2": 21,
}
TYPES = {"u32": 1, "f32": 2}
GROUPS = ("serial", "tuning", "receipt", "boot", "store", "commission", "rotor", "derived", "status")
ACCESS = ("ro", "rw", "tuning", "trim")
BOUND_REFS = ("runtime_iq_limit", "current_ceiling", "tuning_current_limit")
REFRESH = ("profile", "current", "velocity")
STRUCT_OF_GROUP = {"serial": "struct foc_serial", "tuning": "struct foc_runtime_tuning"}
GENERATED = "Generated by scripts/gen/gen_parameters.py from firmware/at32f415/parameters.json; do not edit."
END = "/* ---------------------------------------- end of file ----------------------------------------- */\n"


def fail(message):
    raise SystemExit(f"gen_parameters: {message}")


def load():
    data = json.loads(SOURCE.read_text(encoding="utf-8"))
    entries = data["parameters"]
    ids, names = set(), set()
    previous = 0
    for entry in entries:
        pid, name = entry["id"], entry["name"]
        if not 0 < pid < 65536 or pid in ids or name in names:
            fail(f"duplicate or invalid id/name {pid} {name}")
        if pid <= previous:
            fail(f"ids must be ascending at {pid}")
        previous = pid
        ids.add(pid)
        names.add(name)
        if entry["type"] not in TYPES or entry["unit"] not in UNITS:
            fail(f"{pid}: bad type or unit")
        if entry["group"] not in GROUPS or entry["access"] not in ACCESS:
            fail(f"{pid}: bad group or access")
        writable = entry["access"] != "ro"
        if writable != ("min" in entry and "max" in entry):
            fail(f"{pid}: writable parameters need min and max, read-only ones none")
        if (entry["access"] in ("rw", "tuning")) != (entry["group"] in STRUCT_OF_GROUP):
            fail(f"{pid}: rw/tuning access needs a serial or tuning field")
        if entry["group"] in STRUCT_OF_GROUP and "field" not in entry:
            fail(f"{pid}: missing field")
        if (entry["access"] == "tuning") != (entry["group"] == "tuning"):
            fail(f"{pid}: tuning access and group go together")
        for bound in ("min", "max"):
            value = entry.get(bound)
            if isinstance(value, dict) and "ref" in value and value["ref"] not in BOUND_REFS:
                fail(f"{pid}: unknown bound ref {value['ref']}")
        for item in entry.get("refresh", []):
            if item not in REFRESH:
                fail(f"{pid}: unknown refresh {item}")
        if entry.get("persist") and not writable:
            fail(f"{pid}: only writable parameters persist")
    return entries


def macro(name):
    return "FOC_PARAM_" + name.upper().replace("-", "_")


def bound_number(value):
    if isinstance(value, dict):
        return value.get("value")
    return value


def c_literal(value, kind):
    if kind == "u32":
        return f"{int(value)}U"
    text = repr(float(value))
    if "e" not in text and "." not in text:
        text += ".0"
    return text + "f"


def c_bound(entry, bound):
    """C initializer of the union and the bound code for min or max."""
    kind = entry["type"]
    member = ".u" if kind == "u32" else ".f"
    value = entry.get(bound)
    if value is None:
        return "{.u = 0U}", "FOC_PARAM_BOUND_CONST"
    if isinstance(value, dict) and "ref" in value:
        return "{.u = 0U}", "FOC_PARAM_BOUND_" + value["ref"].upper()
    expression = value["c"] if isinstance(value, dict) else c_literal(value, kind)
    return f"{{{member} = {expression}}}", "FOC_PARAM_BOUND_CONST"


def flags(entry):
    names = []
    if entry.get("calibration"):
        names.append("FOC_PARAM_FLAG_CALIBRATION")
    if entry.get("trip"):
        names.append("FOC_PARAM_FLAG_TRIP")
    refresh = entry.get("refresh", [])
    if "profile" in refresh:
        names.append("FOC_PARAM_FLAG_REFRESH_PROFILE")
    if "current" in refresh:
        names.append("FOC_PARAM_FLAG_REDESIGN_CURRENT")
    if "velocity" in refresh:
        names.append("FOC_PARAM_FLAG_REDESIGN_VELOCITY")
    if entry.get("persist"):
        names.append("FOC_PARAM_FLAG_PERSIST")
    if entry.get("allowed"):
        names.append("FOC_PARAM_FLAG_ALLOWED_SET")
    return " | ".join(names) if names else "0U"


def header(entries):
    ids = "\n".join(f"    {macro(e['name'])} = {e['id']}," for e in entries)
    units = "\n".join(f"    FOC_PARAM_UNIT_{k.upper().replace('/', '_PER_').replace('*', '_').replace('^', '').replace('(', '').replace(')', '')} = {v},"
                      for k, v in UNITS.items())
    groups = "\n".join(f"    FOC_PARAM_GROUP_{g.upper()}," for g in GROUPS)
    access = "\n".join(f"    FOC_PARAM_ACCESS_{a.upper()}," for a in ACCESS)
    bounds = "\n".join(f"    FOC_PARAM_BOUND_{b.upper()}," for b in BOUND_REFS)
    return f"""/**
 * @file    foc_parameter_table.h
 * @brief   Board1 UART/CAN parameter table: IDs, wire types, units, access and bounds.
 * @version v0.1.0
 * @date    2026.11.24
 *
 * Design overview
 * ---------------
 * {GENERATED}
 * One entry per parameter, ascending by ID. A serial or tuning entry names the
 * field it reads and writes (byte offset into struct foc_serial or struct
 * foc_runtime_tuning); other groups are served by foc_serial.c. A persistent
 * entry also names its field in struct foc_board_settings for the TLV store.
 *
 * Usage example
 * -------------
 * const struct foc_parameter_entry *entry = foc_parameter_find(id);
 *
 * Ownership / lifecycle / context
 * -------------------------------
 * Read-only data in flash; safe from any context.
 *
 * Failure / recovery
 * ------------------
 * foc_parameter_find() returns NULL for an unknown ID.
 */
#pragma once

/* Includes --------------------------------------------------------------------- */

#include <stdbool.h>
#include <stddef.h>
#include <stdint.h>

/* Public Types ---------------------------------------------------------------- */

/** Parameter IDs on the wire. */
enum foc_parameter_id {{
{ids}
}};

/** Wire type codes. */
enum foc_parameter_type {{
    FOC_PARAM_TYPE_U32 = 1,
    FOC_PARAM_TYPE_F32 = 2,
}};

/** Wire unit codes. */
enum foc_parameter_unit {{
{units}
}};

/** Who serves the value. */
enum foc_parameter_group {{
{groups}
}};

/** Write access: read only, Foreground RAM, H0 tuning mailbox, calibration trim. */
enum foc_parameter_access {{
{access}
}};

/** Bound source: the constant in the entry, or a live value. */
enum foc_parameter_bound {{
    FOC_PARAM_BOUND_CONST = 0,
{bounds}
}};

/** Entry flags. */
enum foc_parameter_flag {{
    FOC_PARAM_FLAG_CALIBRATION = 1U << 0,
    FOC_PARAM_FLAG_TRIP = 1U << 1,
    FOC_PARAM_FLAG_REFRESH_PROFILE = 1U << 2,
    FOC_PARAM_FLAG_REDESIGN_CURRENT = 1U << 3,
    FOC_PARAM_FLAG_REDESIGN_VELOCITY = 1U << 4,
    FOC_PARAM_FLAG_PERSIST = 1U << 5,
    FOC_PARAM_FLAG_ALLOWED_SET = 1U << 6,
}};

/** A 32-bit wire value. */
union foc_parameter_value {{
    uint32_t u;
    float f;
}};

/** One parameter. */
struct foc_parameter_entry {{
    uint16_t id;
    /** Byte offset of the field (serial and tuning groups), 0 otherwise. */
    uint16_t offset;
    /** Byte offset in struct foc_board_settings when persistent, FOC_PARAM_NO_PERSIST otherwise. */
    uint16_t persist_offset;
    uint8_t unit;
    uint8_t group;
    uint8_t flags;
    /** enum foc_parameter_type, enum foc_parameter_access and two enum foc_parameter_bound. */
    uint8_t type : 2;
    uint8_t access : 2;
    uint8_t min_bound : 2;
    uint8_t max_bound : 2;
    union foc_parameter_value minimum;
    union foc_parameter_value maximum;
}};

/* Public Macros ---------------------------------------------------------------- */

#define FOC_PARAMETER_COUNT         {len(entries)}U
#define FOC_PARAMETER_PERSIST_COUNT {sum(1 for e in entries if e.get("persist"))}U
#define FOC_PARAM_NO_PERSIST        0xFFFFU

/* Public Functions ------------------------------------------------------------ */

/** The table, ascending by ID. */
extern const struct foc_parameter_entry foc_parameter_table[FOC_PARAMETER_COUNT];

/** Binary search by ID; NULL when unknown. */
const struct foc_parameter_entry *foc_parameter_find(uint16_t id);

/** True unless the entry restricts the value to a set that does not contain it. */
bool foc_parameter_allowed(const struct foc_parameter_entry *entry, uint32_t value);

{END}"""


def source(entries):
    rows = []
    allowed = []
    for e in entries:
        kind = e["type"]
        minimum, min_bound = c_bound(e, "min")
        maximum, max_bound = c_bound(e, "max")
        offset = f"offsetof({STRUCT_OF_GROUP[e['group']]}, {e['field']})" if e["group"] in STRUCT_OF_GROUP else "0U"
        persist = f"offsetof(struct foc_board_settings, {e['persist']})" if e.get("persist") else "FOC_PARAM_NO_PERSIST"
        rows.append(f"""    {{
        .id = {macro(e['name'])},
        .offset = {offset},
        .persist_offset = {persist},
        .unit = {UNITS[e['unit']]}U,
        .group = FOC_PARAM_GROUP_{e['group'].upper()},
        .flags = {flags(e)},
        .type = FOC_PARAM_TYPE_{kind.upper()},
        .access = FOC_PARAM_ACCESS_{e['access'].upper()},
        .min_bound = {min_bound},
        .max_bound = {max_bound},
        .minimum = {minimum},
        .maximum = {maximum},
    }},""")
        if e.get("allowed"):
            values = ", ".join(f"{v}U" for v in e["allowed"])
            allowed.append(f"    case {macro(e['name'])}: {{\n        static const uint32_t set[] = {{{values}}};\n"
                           f"        for (size_t index = 0U; index < sizeof set / sizeof set[0]; ++index) {{\n"
                           f"            if (set[index] == value) {{\n                return true;\n            }}\n        }}\n"
                           f"        return false;\n    }}")
    asserts = []
    for e in entries:
        if e["group"] in STRUCT_OF_GROUP:
            asserts.append(f"_Static_assert(sizeof((({STRUCT_OF_GROUP[e['group']]} *)0)->{e['field']}) == 4U, \"{e['name']}\");")
        if e.get("persist"):
            asserts.append(f"_Static_assert(sizeof(((struct foc_board_settings *)0)->{e['persist']}) == 4U, \"{e['name']} persist\");")
    allowed_cases = "\n".join(allowed)
    table = "\n".join(rows)
    checks = "\n".join(asserts)
    return f"""/**
 * @file    foc_parameter_table.c
 * @brief   Board1 UART/CAN parameter table.
 * @version v0.1.0
 * @date    2026.11.24
 *
 * Implementation role
 * -------------------
 * - {GENERATED}
 * - constant bounds use the firmware macros named in the JSON; the unit test
 *   test-foc-parameter-table checks them against the documented values
 */

/* Includes --------------------------------------------------------------------- */

#include "foc_parameter_table.h"

#include "foc_board_profile.h"
#include "foc_board_store.h"
#include "foc_runtime.h"
#include "foc_serial.h"

/* Private Helpers -------------------------------------------------------------- */

_Static_assert(sizeof(struct foc_parameter_entry) == 20U, "entry packing");
{checks}

/* Public Functions ------------------------------------------------------------- */

const struct foc_parameter_entry foc_parameter_table[FOC_PARAMETER_COUNT] = {{
{table}
}};

const struct foc_parameter_entry *foc_parameter_find(uint16_t id)
{{
    size_t low = 0U;
    size_t high = FOC_PARAMETER_COUNT;
    while (low < high) {{
        const size_t middle = low + (high - low) / 2U;
        if (foc_parameter_table[middle].id == id) {{
            return &foc_parameter_table[middle];
        }}
        if (foc_parameter_table[middle].id < id) {{
            low = middle + 1U;
        }} else {{
            high = middle;
        }}
    }}
    return NULL;
}}

bool foc_parameter_allowed(const struct foc_parameter_entry *entry, uint32_t value)
{{
    if (entry == NULL || (entry->flags & FOC_PARAM_FLAG_ALLOWED_SET) == 0U) {{
        return true;
    }}
    switch (entry->id) {{
{allowed_cases}
    default:
        return true;
    }}
}}

{END}"""


def documented(entries):
    rows = []
    for e in entries:
        lo, hi = bound_number(e.get("min")), bound_number(e.get("max"))
        kind = e["type"]

        def bits(value):
            if value is None:
                return "0U, false"
            if kind == "u32":
                return f"{int(value)}U, true"
            return f"0x{struct.unpack('<I', struct.pack('<f', float(value)))[0]:08X}U, true"
        rows.append(f"    {{{e['id']}U, {bits(lo)}, {bits(hi)}}},")
    body = "\n".join(rows)
    return f"""/**
 * @file    foc_parameter_documented.h
 * @brief   Documented numeric bounds from parameters.json, for test-foc-parameter-table.
 * @version v0.1.0
 * @date    2026.11.24
 *
 * Design overview
 * ---------------
 * {GENERATED}
 * One row per parameter: ID, minimum bits and presence, maximum bits and presence.
 *
 * Usage example
 * -------------
 * Compare each constant bound of foc_parameter_table with its documented row.
 *
 * Ownership / lifecycle / context
 * -------------------------------
 * Test data only; not linked into any image.
 *
 * Failure / recovery
 * ------------------
 * A mismatch means a firmware macro and the JSON value disagree.
 */
#pragma once

/* Includes --------------------------------------------------------------------- */

#include <stdbool.h>
#include <stdint.h>

/* Public Types ---------------------------------------------------------------- */

struct foc_parameter_documented {{
    uint16_t id;
    uint32_t minimum;
    bool has_minimum;
    uint32_t maximum;
    bool has_maximum;
}};

/* Public Functions ------------------------------------------------------------ */

static const struct foc_parameter_documented foc_parameter_documented[] = {{
{body}
}};

{END}"""


def python_module(entries):
    lines = []
    for e in entries:
        info = {
            "id": e["id"], "type": e["type"], "unit": e["unit"], "access": e["access"],
            "group": e["group"], "persist": bool(e.get("persist")), "unit_code": UNITS[e["unit"]],
            "calibration": bool(e.get("calibration")),
            "min": bound_number(e.get("min")) if not (isinstance(e.get("min"), dict) and "ref" in e["min"]) else None,
            "max": bound_number(e.get("max")) if not (isinstance(e.get("max"), dict) and "ref" in e["max"]) else None,
            "brief": e["brief"],
        }
        lines.append(f"    {e['name']!r}: {info!r},")
    body = "\n".join(lines)
    return f'''"""Board1 UART/CAN parameters.

{GENERATED}
"""

PARAMETER_INFO = {{
{body}
}}

# Name -> wire ID.
PARAMETERS = {{name: info["id"] for name, info in PARAMETER_INFO.items()}}
# Wire ID -> "u32" or "f32".
PARAMETER_TYPES = {{info["id"]: info["type"] for info in PARAMETER_INFO.values()}}
# Names saved by PARAM_SAVE.
PERSISTENT_PARAMETERS = tuple(name for name, info in PARAMETER_INFO.items() if info["persist"])
'''


def manual(entries):
    def show(value, unit):
        if value is None:
            return ""
        if isinstance(value, dict) and "ref" in value:
            return {"runtime_iq_limit": "boot q-current limit", "current_ceiling": "board ceiling",
                    "tuning_current_limit": "ID 68"}[value["ref"]]
        number = bound_number(value)
        return f"{number:g}" if isinstance(number, float) else str(number)

    access = {"ro": "RO", "rw": "RW", "tuning": "RW (DISABLED, H0)", "trim": "RW (trim)"}
    rows = []
    for e in entries:
        lo, hi = show(e.get("min"), e["unit"]), show(e.get("max"), e["unit"])
        span = f"{lo} … {hi}" if lo or hi else ""
        if e.get("allowed"):
            span = " / ".join(str(v) for v in e["allowed"])
        unit = "" if e["unit"] == "none" else e["unit"]
        rows.append(f"| {e['id']} | `{e['name']}` | {e['type']} | {unit} | {access[e['access']]} | {span} | "
                    f"{'yes' if e.get('persist') else ''} | {e['brief']} |")
    body = "\n".join(rows)
    return f"""# FalconFOC V2 Board1 parameters

{GENERATED}

UART V1 `PARAM_READ`/`PARAM_WRITE` and CANSimple SDO (RxSdo/TxSdo) use these IDs.
"RW (DISABLED, H0)" writes are accepted only while DISABLED and are applied by H0
(receipt in IDs 60–62). "Saved" parameters are written by `PARAM_SAVE` into the TLV
settings record. Semantics, derivations and calibration stages are in the
[parameter contract](superpowers/specs/2026-11-22-falconfoc-v2-parameter-contract-design.md).

| ID | Name | Type | Unit | Access | Range | Saved | Description |
| ---: | --- | --- | --- | --- | --- | --- | --- |
{body}
"""


def outputs(entries):
    return {
        "firmware/at32f415/include/foc_parameter_table.h": header(entries),
        "firmware/at32f415/src/foc_parameter_table.c": source(entries),
        "firmware/at32f415/tests/foc_parameter_documented.h": documented(entries),
        "tools/falconfoc-cli/falconfoc_params.py": python_module(entries),
        "docs/parameters.md": manual(entries),
    }


def main():
    check = "--check" in sys.argv[1:]
    stale = []
    for relative, text in outputs(load()).items():
        path = ROOT / relative
        current = path.read_text(encoding="utf-8").replace("\r\n", "\n") if path.is_file() else None
        if current == text:
            continue
        if check:
            stale.append(relative)
        else:
            path.write_text(text, encoding="utf-8", newline="\n")
            print(f"wrote {relative}")
    if stale:
        print("gen_parameters: stale generated files: " + ", ".join(stale))
        return 1
    if check:
        print("gen_parameters: generated files are current")
    return 0


if __name__ == "__main__":
    sys.exit(main())
